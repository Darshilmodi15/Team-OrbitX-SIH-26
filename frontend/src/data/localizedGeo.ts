/**
 * Returns localized name for a city ID with fallback to English
 */
export function getLocalizedCityName(cityId: string, fallbackName: string, lang: string): string {
  const normId = cityId.toLowerCase().trim();
  const entry = LOCALIZED_CITIES[normId];
  if (!entry) return fallbackName;
  const langKey = lang as keyof LocalizedEntityName;
  return (entry[langKey] as string) || entry.en || fallbackName;
}

/**
 * Returns localized name and description for an Indian port
 */
export function getLocalizedPort(port: { id: string; name: string; description?: string; type?: string }, lang: string) {
  const normId = port.id.toLowerCase().trim();
  const entry = LOCALIZED_PORTS[normId];
  const langKey = lang as keyof LocalizedEntityName;

  if (!entry) {
    return {
      name: port.name,
      type: port.type || 'Port',
      description: port.description || '',
    };
  }

  return {
    name: (entry.name[langKey] as string) || entry.name.en || port.name,
    type: (entry.type[langKey] as string) || entry.type.en || port.type || 'Port',
    description: (entry.description[langKey] as string) || entry.description.en || port.description || '',
  };
}

/**
 * Returns localized name and description for a marine geofence
 */
export function getLocalizedGeofence(geofence: { id: string; name: string; description?: string }, lang: string) {
  const normId = geofence.id.toLowerCase().trim();
  const entry = LOCALIZED_GEOFENCES[normId];
  const langKey = lang as keyof LocalizedEntityName;

  if (!entry) {
    return {
      name: geofence.name,
      description: geofence.description || '',
    };
  }

  return {
    name: (entry.name[langKey] as string) || entry.name.en || geofence.name,
    description: (entry.description[langKey] as string) || entry.description.en || geofence.description || '',
  };
}

/**
 * Returns localized water body name (e.g. Arabian Sea -> અરબી સમુદ્ર)
 */
export function getLocalizedSeaName(seaId: string, fallback: string, lang: string): string {
  const normId = seaId.toLowerCase().trim();
  const entry = LOCALIZED_SEAS[normId];
  const langKey = lang as keyof LocalizedEntityName;
  return (entry?.[langKey] as string) || entry?.en || fallback;
}
