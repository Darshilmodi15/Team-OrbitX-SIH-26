export const getStrings = (lang: string): UIStrings => {
  if (lang === 'en' || !isLanguageCode(lang)) return en;
  const langKey = lang as Exclude<LanguageCode, 'en'>;
  const specific = localized[langKey];
  if (!specific) return en;
  return { ...en, ...specific };
};
