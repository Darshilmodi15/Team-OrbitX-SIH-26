const DICTS: Record<LangCode, Dict> = {
  en,
  hi,
  gu,
  mr,
  ta,
  te,
  ml,
  bn,
  kn,
  or,
  pa,
};

const STORAGE_KEY = "orca.lang";

type I18nValue = {
  lang: LangCode;
  setLang: (l: LangCode) => void;
  t: (key: TKey) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangCode>(() => {
    try {
      const stored = window.localStorage.getItem(STORAGE_KEY) as LangCode | null;
      if (stored && stored in DICTS) return stored;
    } catch {
      /* ignore */
    }
    return "en";
  });

  useEffect(() => {
    try {
      const stored = window.localStorage.getItem(STORAGE_KEY) as LangCode | null;
      if (stored && stored in DICTS) setLangState(stored);
    } catch {
      /* storage unavailable */
    }
  }, []);

  useEffect(() => {
    if (typeof document !== "undefined") document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((l: LangCode) => {
    setLangState(l);
    try {
      window.localStorage.setItem(STORAGE_KEY, l);
      window.localStorage.setItem("orca-lang", l);
    } catch {
      /* ignore */
    }
  }, []);

  const t = useCallback(
    (key: TKey) => DICTS[lang]?.[key] ?? en[key] ?? (key as string),
    [lang],
  );

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
