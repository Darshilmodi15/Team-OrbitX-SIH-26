function getCompass(deg: number | null | undefined, lang: string): string {
  if (deg == null) return "—";
  const list = COMPASS_DIRECTIONS[lang] || COMPASS_DIRECTIONS.en;
  const idx = Math.round(((deg % 360) + 360) % 360 / 45) % 8;
  return list[idx];
}

